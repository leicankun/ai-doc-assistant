def write_dataset(directory):
    directory = Path(directory)
    docs = directory / 'documents'
    docs.mkdir(parents=True, exist_ok=True)
    for name, (title, paragraphs) in DOCUMENTS.items():
        content = '# ' + title + '\n\n' + '\n\n'.join(
            f'## 第 {n} 节\n\n{paragraph}' for n, paragraph in enumerate(paragraphs, 1)) + '\n'
        (docs / name).write_text(content, encoding='utf-8')
    for filename, items in [('questions.jsonl',questions()),('memory.jsonl',memory_scenarios())]:
        (directory / filename).write_text(''.join(json.dumps(q,ensure_ascii=False)+'\n' for q in items),encoding='utf-8')


